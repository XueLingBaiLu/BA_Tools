using System;
using System.Collections.Generic;
using System.IO;
using System.Reflection;
using System.Text;

namespace BaModProbe
{
    /// <summary>
    /// The dump contract shared with the offline comparator.
    ///
    /// Table names are NOT hand-transcribed: they are discovered from the live
    /// DataBaseSourceData type as "every property whose type is
    /// Il2CppBrokenArrow.DataBase.Driver.Table&lt;T&gt;". The proxy assembly carries each table
    /// twice (once as 'Units', once as '_Units_k__BackingField'); the backing-field twins are
    /// filtered out, which leaves exactly the 24 table names.
    ///
    /// Column names come from _work/columns.json, generated by tools/check_columns.py from
    /// DataBaseCompiled/&lt;ver&gt;/*.json -- the same file the comparator reads, so the two sides
    /// cannot drift apart. When that file is absent the probe falls back to reflecting over the
    /// row type and says so in the dump ('probe.columns_source').
    /// </summary>
    internal static class Contract
    {
        internal const string TableNamespace = "Il2CppBrokenArrow.DataBase.Driver";
        internal const string BackingSuffix = "_k__BackingField";

        private static Dictionary<string, string[]> _columns;

        internal static bool HasColumnManifest { get { return _columns != null; } }
        internal static int TableCountInManifest { get { return _columns == null ? 0 : _columns.Count; } }

        /// <summary>Every Table&lt;T&gt; property of the live source object, backing-field twins removed.</summary>
        internal static List<string> DiscoverTables(Type sourceDataType)
        {
            var names = new List<string>();
            if (sourceDataType == null) return names;
            foreach (PropertyInfo p in sourceDataType.GetProperties(RowAccess.PubInst))
            {
                Type pt = p.PropertyType;
                if (!pt.IsGenericType) continue;
                if (pt.GetGenericArguments().Length != 1) continue;
                Type gen = pt.GetGenericTypeDefinition();
                if (gen.Namespace != TableNamespace) continue;
                if (!gen.Name.StartsWith("Table", StringComparison.Ordinal)) continue;
                if (p.Name.StartsWith("_", StringComparison.Ordinal)
                    && p.Name.EndsWith(BackingSuffix, StringComparison.Ordinal)) continue;
                names.Add(p.Name);
            }
            names.Sort(StringComparer.Ordinal);
            return names;
        }

        internal static void LoadColumns()
        {
            _columns = null;
            try
            {
                if (!File.Exists(ProbePaths.ColumnsFile))
                {
                    ProbeLog.Warn("no column manifest at " + ProbePaths.ColumnsFile + " -- falling back to reflection");
                    return;
                }
                object rootObj = JsonReader.Parse(File.ReadAllText(ProbePaths.ColumnsFile, Encoding.UTF8));
                var root = rootObj as Dictionary<string, object>;
                if (root == null) { ProbeLog.Warn("column manifest is not a JSON object"); return; }
                object tablesObj;
                if (!root.TryGetValue("tables", out tablesObj)) { ProbeLog.Warn("column manifest has no 'tables'"); return; }
                var tables = tablesObj as Dictionary<string, object>;
                if (tables == null) { ProbeLog.Warn("column manifest 'tables' is not an object"); return; }

                var map = new Dictionary<string, string[]>(StringComparer.Ordinal);
                foreach (KeyValuePair<string, object> kv in tables)
                {
                    var list = kv.Value as List<object>;
                    if (list == null) continue;
                    var cols = new string[list.Count];
                    for (int i = 0; i < list.Count; i++) cols[i] = Convert.ToString(list[i]);
                    map[kv.Key] = cols;
                }
                _columns = map;
                ProbeLog.Info("column manifest loaded: " + map.Count + " tables, " + TotalColumns(map) + " columns");
            }
            catch (Exception ex)
            {
                _columns = null;
                ProbeLog.Error("failed to load column manifest", ex);
            }
        }

        private static int TotalColumns(Dictionary<string, string[]> map)
        {
            int n = 0;
            foreach (KeyValuePair<string, string[]> kv in map) n += kv.Value.Length;
            return n;
        }

        /// <summary>Contract columns for a table, or null when there is no manifest entry.</summary>
        internal static string[] ColumnsFor(string table, Type rowType)
        {
            string[] cols;
            if (_columns != null && _columns.TryGetValue(table, out cols) && cols.Length > 0) return cols;
            return ReflectColumns(rowType);
        }

        /// <summary>
        /// Fallback column set: public instance properties of the row type that carry a scalar
        /// value, with the Il2CppInterop backing-field twins removed. Reference-typed members
        /// (nav properties such as Options.Armor) are deliberately excluded here; in manifest
        /// mode they simply never appear because DataBaseCompiled does not list them either.
        /// </summary>
        internal static string[] ReflectColumns(Type rowType)
        {
            if (rowType == null) return new string[0];
            var names = new List<string>();
            foreach (PropertyInfo p in rowType.GetProperties(RowAccess.PubInst))
            {
                if (p.Name.StartsWith("_", StringComparison.Ordinal)
                    && p.Name.EndsWith(BackingSuffix, StringComparison.Ordinal)) continue;
                if (p.GetIndexParameters().Length != 0) continue;
                if (!p.CanRead) continue;
                if (!RowAccess.IsPrimitiveish(p.PropertyType)) continue;
                names.Add(p.Name);
            }
            names.Sort(StringComparer.Ordinal);
            return names.ToArray();
        }
    }
}
